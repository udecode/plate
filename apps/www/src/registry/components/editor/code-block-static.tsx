function getCodeBlockLanguageLabel(lang?: string | null) {
  const value = lang?.trim();

  if (!value) return null;

  return (
    codeBlockLanguages.find((language) => language.value === value)?.label ??
    value
  );
}

export function CodeBlockElementStatic({
  showLanguageLabel = true,
  ...props
}: EditorElementProps<typeof BaseCodeBlockPlugin> & {
  showLanguageLabel?: boolean;
}) {
  const languageLabel = getCodeBlockLanguageLabel(props.element.language);

  return (
    <EditorElement
      className={`py-1 ${codeSyntaxClassName}`}
      {...props}
      attributes={{ ...props.attributes, dir: 'ltr' }}
    >
      <div className="relative rounded-md bg-muted/50">
        {showLanguageLabel && languageLabel && (
          <div
            className="absolute end-1 top-1 z-10 flex h-6 items-center px-2 text-xs text-muted-foreground select-none"
            contentEditable={false}
          >
            {languageLabel}
          </div>
        )}

        <pre className="overflow-x-auto p-8 pe-4 font-mono text-sm leading-[normal] [tab-size:2] print:break-inside-avoid">
          <code>{props.children}</code>
        </pre>
      </div>
    </EditorElement>
  );
}

/**
 * DOCX-compatible code block components.
 * Uses inline styles for proper rendering in Word documents.
 */

export function CodeBlockElementDocx(
  props: EditorElementProps<typeof BaseCodeBlockPlugin>
) {
  return (
    <EditorElement {...props}>
      <div
        data-docx-preserve-whitespace=""
        style={{
          backgroundColor: '#f5f5f5',
          border: '1px solid #e0e0e0',
          fontFamily: "'Courier New', Consolas, monospace",
          fontSize: '10pt',
          margin: '8pt 0',
          padding: '12pt',
          whiteSpace: 'pre-wrap',
        }}
      >
        {props.children}
      </div>
    </EditorElement>
  );
}

