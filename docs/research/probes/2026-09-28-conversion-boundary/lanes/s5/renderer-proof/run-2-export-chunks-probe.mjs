import { chromium } from '/Users/zbeyens/git/plate-2/node_modules/@playwright/test/index.mjs';
const base = process.argv[2];
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1280, height: 720 }, acceptDownloads: true });
const page = await context.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
const chunks = [];
let armed = false;
page.on('request', (r) => { if (armed && r.url().includes('/_next/static/chunks/')) chunks.push(r.url().split('/_next/static/chunks/')[1]); });
await page.goto(`${base}/blocks/docx-demo`, { waitUntil: 'networkidle' });
await page.getByRole('button', { name: 'Import' }).waitFor({ timeout: 30000 });
armed = true;
await page.getByRole('button', { name: 'Export' }).click();
const item = page.getByRole('menuitem', { exact: true, name: 'Export as HTML' });
await item.waitFor();
const download = page.waitForEvent('download', { timeout: 15000 });
await item.click();
const d = await download;
console.log(JSON.stringify({ download: d.suggestedFilename(), chunksLoadedDuringExport: chunks, pageErrors: errors }));
await browser.close();
